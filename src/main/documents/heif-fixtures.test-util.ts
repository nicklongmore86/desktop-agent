/** `bytes` with the primary image's `ispe` claiming `width` x `height`. */
export function withIspe(bytes: Uint8Array, width: number, height: number): Uint8Array {
  const copy = new Uint8Array(bytes)
  const at = Buffer.from(copy).indexOf('ispe')
  if (at < 0) throw new Error('no ispe box')
  const view = new DataView(copy.buffer)
  view.setUint32(at + 8, width)
  view.setUint32(at + 12, height)
  return copy
}
